#!/usr/bin/env python3
"""Generate victronble/products.py from the product table of victron-ble.

    git clone https://github.com/keshavdv/victron-ble
    tools/gen_products.py victron-ble/victron_ble/devices/base.py > victronble/products.py

victron-ble is public domain (The Unlicense). The file is only parsed as text,
nothing from it is imported or executed.
"""

import re
import sys

HEADER = '''"""Names of Victron products by product id.

Generated by tools/gen_products.py from the MODEL_ID_MAPPING table of
https://github.com/keshavdv/victron-ble (public domain, The Unlicense).
"""

NAMES = {
'''

FOOTER = '''}


def name(product_id, generic=None):
    """Product name; for unknown ids the generic name plus the id."""
    if product_id is None:
        return generic or "Unknown product"
    known = NAMES.get(product_id)
    if known:
        return known
    return "%s (0x%04X)" % (generic or "Victron product", product_id)
'''


def main(path):
    src = open(path, encoding="utf-8").read()
    start = src.index("MODEL_ID_MAPPING = {")
    end = src.index("\n}", start)
    entries = re.findall(r'^\s*(0x[0-9A-Fa-f]+):\s*"((?:[^"\\]|\\.)*)",?\s*$', src[start:end], re.M)
    if len(entries) < 500:
        sys.exit("only %d entries found, has the table format changed?" % len(entries))
    names = {}
    for pid, text in entries:
        names[int(pid, 16)] = text.replace("\\", "")
    out = [HEADER]
    for pid in sorted(names):
        out.append("    0x%04X: %r,\n" % (pid, names[pid]))
    out.append(FOOTER)
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
